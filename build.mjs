import {mkdir,rm,copyFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=path.dirname(fileURLToPath(import.meta.url));
const output=path.join(root,'dist');
if(path.dirname(output)!==root||path.basename(output)!=='dist')throw new Error('Destino inválido.');
const check=spawnSync(process.execPath,[path.join(root,'check.mjs')],{stdio:'inherit'});
if(check.status!==0)process.exit(check.status??1);
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
const files=["Barlow-Condensed-OFL.txt", "DM-Sans-OFL.txt", "app.js", "barlow-condensed-800.ttf", "brand.webp", "cacao.webp", "dm-sans-400.ttf", "dm-sans-700.ttf", "final-details.css", "founders.webp", "hand.webp", "index.html", "logo-transparent.png", "lucuma.webp", "menta.webp", "mini.webp", "product-polish.css", "refinements.css", "styles.css", "superfoods.webp"];
for(const file of files)await copyFile(path.join(root,file),path.join(output,file));
await writeFile(path.join(output,'.nojekyll'),'');
console.log('Producción lista en dist/.');
